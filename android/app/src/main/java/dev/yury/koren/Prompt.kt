package dev.yury.koren

/**
 * Инструкция для нейросети: как писать файлы, которые это приложение покажет
 * правильно. Живёт внутри приложения — в рабочей папке ничего не создаётся.
 *
 * Достать её можно двумя путями:
 *   1. кнопкой «Скопировать промпт» в настройках — попадёт в буфер обмена;
 *   2. запросом к приложению из терминала, без рута:
 *
 *        content query --uri content://dev.yury.koren/prompt
 */
object Prompt {

    val TEXT: String = """
        Пиши файл для приложения «Корень» — читалки математики под Android.
        Это обычный markdown с формулами. Соблюдай правила ниже, иначе файл
        отрисуется неправильно.

        ФАЙЛ
        - Расширение .md, кодировка UTF-8, переводы строк LF.
        - Имя файла — человеческое, оно показывается в списке: «Шпора — матан.md».

        ТЕКСТ
        - Обычный markdown: # ## ### заголовки, **жирный**, ~~зачёркнутый~~,
          `код`, > цитата, таблицы через |, списки через -.
        - Заголовки уровня ## попадают в оглавление, по ним листают шпору.
          Разбивай длинный файл на ## разделы — это единственная навигация.

        ОТМЕТКИ — ГЛАВНОЕ ПРАВИЛО
        Две разновидности строк, различаются скобками:

            - [ ] Вывести производную по определению     ← ЗАДАЧА, квадратные
            - ( ) Ряды Фурье                             ← ТЕМА, круглые

        Задача — то, что делают один раз и забывают: решить, вывести, доказать.
        Тема — то, что изучают: раздел, понятие, метод.

        Три состояния у обеих:
            - [ ] не начато        - ( ) не начато
            - [~] в работе         - (~) разбираю
            - [x] сделано          - (x) пройдено

        Сделанная задача перечёркивается, пройденная тема — нет, она просто гаснет.
        Обычный пункт списка (просто «- текст») отметкой не считается.

        ФОРМУЛЫ
        - В строке — одинарные доллары:  масса ${'$'}m${'$'} и скорость ${'$'}v${'$'}
        - Отдельной строкой — двойные:   ${'$'}${'$'}\int_0^1 x\,dx = \tfrac12${'$'}${'$'}
        - Внутри долларов — только математика: \frac \dfrac \sqrt \int \iint \oint
          \sum \prod \lim \partial \nabla \binom \cfrac \underbrace \overbrace
          \begin{pmatrix} \begin{bmatrix} \begin{vmatrix} \begin{cases}
          \begin{aligned} \substack \mathbb \mathcal \operatorname \text и подобное.
        - Русский текст внутри формулы оборачивай в \text{...} — он отрисуется.
        - НЕ пиши команды документа: \documentclass, \usepackage, \begin{document},
          \section, tcolorbox, tikz, \newcommand. Их некому выполнять, файл покраснеет.
        - Длинные формулы лучше разбивать: экран узкий, иначе придётся листать вбок.

        ЧЕРТЕЖИ И ГРАФИКИ
        - Только встроенным SVG прямо в файле: <svg viewBox="0 0 320 180">...</svg>
        - Ссылок наружу быть не должно — интернета у приложения нет.
        - Для линий осей и подписей используй stroke="currentColor", тогда чертёж
          подстроится под светлую и тёмную тему.

        ЧЕГО НЕ ДЕЛАТЬ
        - Не вставляй HTML кроме <svg>.
        - Не ставь ссылки на картинки и файлы.
        - Не пиши служебных шапок с настройками в начале файла — тип файла
          приложение определяет само по тому, что внутри.

        ОБРАЗЕЦ

        # Матанализ — производные

        ## Определение

        - ( ) Предел разностного отношения
        - (x) Таблица производных

        ${'$'}${'$'}f'(x) = \lim_{\Delta x \to 0} \frac{f(x + \Delta x) - f(x)}{\Delta x}${'$'}${'$'}

        ## Задачи

        - [x] Вывести производную ${'$'}f(x)=\sqrt{x^3}${'$'}
        - [~] Доказать ${'$'}\dfrac{\partial}{\partial x}(x^{\top}Ax) = 2Ax${'$'}
        - [ ] Разобрать случай ${'$'}f(x)=x^{2/3}${'$'} в нуле
    """.trimIndent()
}
